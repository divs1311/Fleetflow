-- One row per *message* received (duplicates still present). Only renaming,
-- typing and simple derived flags: no business logic in staging.
select
    event_id,
    schema_version,
    event_type,
    event_ts_utc,
    {{ to_ist('event_ts_utc') }}                              as event_ts_ist,
    produced_at_utc,
    trip_id,
    city_code,
    customer_id,
    vehicle_type,
    driver_id,
    vehicle_id,
    lat,
    lng,
    (lat is null or lng is null)                              as is_gps_missing,
    pickup_lat,
    pickup_lng,
    drop_lat,
    drop_lng,
    estimated_fare,
    fare_amount,
    distance_km,
    payment_mode,
    cancelled_by,
    cancellation_reason,
    app_version,
    -- device upload delay; > 1h means the event arrived late from the phone
    coalesce(produced_at_utc - event_ts_utc > interval 1 hour, false) as is_late_arrival,
    cast(event_date as date)                                  as partition_event_date,
    _kafka_partition,
    _kafka_offset,
    _loaded_at_utc,
    _batch_id
from {{ source('raw', 'trip_events') }}
